def face_check_required(pick):
    """True for a series that may reach the head: the plan's FACE CHECK slots (head and neck stand-ins, PET and PET-CT
    studies), body part NECK / HEAD / WHOLEBODY, every PT, and, wider than the plan, every CT that covers the chest or
    has no body part (its top can reach the neck) and every chest radiograph (the lateral view)."""
    slot = pick["slot"].replace(" ", "_")
    bp = (pick.get("bp") or "").upper()
    desc = (pick.get("desc") or "").upper()
    if slot in FACE_CHECK_SLOTS or bp in FACE_CHECK_BODY_PARTS or pick["modality"] in ("PT", "DX", "CR"):
        return True
    return pick["modality"] == "CT" and (not bp or "CHEST" in bp or "NECK" in bp or "CHEST" in desc
                                         or "THORAX" in desc)


