# ------------------------------------------------------------------------ scanning the library
def sha256_of(path, chunk=1 << 20):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(chunk), b""):
            h.update(block)
    return h.hexdigest()


def dcm_files(folder):
    return sorted(p for p in Path(folder).glob("*.dcm") if p.is_file())


def read_header(path):
    import pydicom
    return pydicom.dcmread(str(path), stop_before_pixels=True, force=True)


def _s(ds, keyword, default=""):
    v = ds.get(keyword, default)
    if v is None:
        return default
    try:
        v = v.value if hasattr(v, "value") else v
    except Exception:
        pass
    if isinstance(v, (list, tuple)) or v.__class__.__name__ == "MultiValue":
        return "\\".join(str(x) for x in v)
    return str(v)


def instance_number(ds, default=0):
    try:
        return int(ds.InstanceNumber)
    except (AttributeError, TypeError, ValueError):
        return default


def z_of(ds):
    try:
        return float(ds.ImagePositionPatient[2])
    except (AttributeError, TypeError, ValueError, IndexError):
        return None


def sorted_instances(folder):
    """[(path, header)] of a series sorted by InstanceNumber (then z position, then file name)."""
    items = []
    for p in dcm_files(folder):
        try:
            ds = read_header(p)
        except Exception:
            continue
        items.append((p, ds))
    items.sort(key=lambda t: (instance_number(t[1]), z_of(t[1]) if z_of(t[1]) is not None else 0.0, t[0].name))
    return items


def series_facts(folder):
    """Header facts of one extracted series: counts, geometry, transfer syntax, burned-in flag (no pixels read)."""
    items = sorted_instances(folder)
    if not items:
        return {"instances": 0}
    first = items[0][1]
    zs = [z for _, ds in items if (z := z_of(ds)) is not None]
    facts = {
        "instances": len(items),
        "dcm_bytes": sum(p.stat().st_size for p, _ in items),
        "transfer_syntax": str(getattr(first.file_meta, "TransferSyntaxUID", "")),
        "photometric": _s(first, "PhotometricInterpretation"),
        "rows": _s(first, "Rows"),
        "columns": _s(first, "Columns"),
        "burned_in_annotation": _s(first, "BurnedInAnnotation", "absent") or "absent",
        "source_sex": _s(first, "PatientSex"),
        "source_age": _s(first, "PatientAge"),
        "body_part_tag": _s(first, "BodyPartExamined"),
        "series_description_tag": _s(first, "SeriesDescription"),
        "header_patient_id": _s(first, "PatientID"),
        "header_study_uid": _s(first, "StudyInstanceUID"),
        "header_series_uid": _s(first, "SeriesInstanceUID"),
        "z_extent_mm": round(max(zs) - min(zs), 1) if len(zs) > 1 else "",
        "instance_numbers": [instance_number(ds) for _, ds in items],
    }
    return facts


def load_qa_results(root):
    p = Path(root) / "qa" / "qa_results.json"
    return json.loads(p.read_text()) if p.exists() else {}


def download_times(root):
    """{series uid: ISO time of its last OK / MISMATCH line in download.log} (falls back to the zip mtime)."""
    p = Path(root) / "download.log"
    out = {}
    if not p.exists():
        return out
    for line in p.read_text(errors="replace").splitlines():
        parts = line.split()
        if len(parts) >= 6 and parts[1] in ("OK", "MISMATCH"):
            out[parts[5].rstrip(":")] = parts[0]
    return out


def burned_in_value(tag_value, text_check):
    """yes | no | unknown, in the DICOM sense of BurnedInAnnotation (text that identifies the patient or the date):
    yes when the tag says YES or the visual check failed; no when the tag is NO or absent and the visual check passed."""
    if str(tag_value).upper() == "YES" or text_check == "fail":
        return "yes"
    if text_check == "pass":
        return "no"
    return "unknown"


def build_rows(root=DEFAULT_ROOT, qa=None):
    root = Path(root)
    qa = load_qa_results(root) if qa is None else qa
    times = download_times(root)
    rows = []
    for pick in load_picks():
        col = COLLECTIONS[pick["collection"]]
        d = series_dir(root, pick)
        zip_path = d.parent / (d.name + ".zip")   # the UID has dots: no with_suffix
        complete = (d / ".complete").exists()
        facts = series_facts(d) if complete else {"instances": 0}
        q = qa.get(pick["series"], {})
        removed = q.get("instances_removed") or []
        deface = q.get("deface_check") or "pending"
        text = q.get("text_check") or "pending"
        notes = [pick.get("note") or ""]
        if pick["collection"] in CHINESE_COLLECTIONS:
            notes.append("Chinese collection")
        if pick["group"].startswith("E "):
            notes.append("head and neck stand-in: not a head and neck cancer patient")
        if q.get("note"):
            notes.append("QA: " + q["note"])
        if complete and facts["instances"] + len(removed) != pick["n"]:
            notes.append(f"instance count {facts['instances']} + {len(removed)} removed differs from the TCIA count {pick['n']}")
        if complete and facts.get("header_series_uid") and facts["header_series_uid"] != pick["series"]:
            notes.append("header SeriesInstanceUID differs from the requested one")
        downloaded = times.get(pick["series"]) or (
            datetime.fromtimestamp(zip_path.stat().st_mtime, timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
            if zip_path.exists() else "")
        rows.append({
            "slot": pick["slot"], "group": pick["group"], "collection": pick["collection"],
            "licence_name": col["licence"][0], "licence_url": col["licence"][1], "collection_doi": col["doi"],
            "collection_page_url": col["page"], "collection_citation": col["citation"], "tcia_citation": TCIA_CITATION,
            "origin_country": col["origin"], "stand_in": pick["group"].startswith("E "),
            "source_patient_id": pick["patient"], "source_study_uid": pick["study"], "source_series_uid": pick["series"],
            "source_study_date": pick.get("studydate") or "", "modality": pick["modality"],
            "body_part": pick.get("bp") or facts.get("body_part_tag") or "",
            "series_description": pick.get("desc") or facts.get("series_description_tag") or "",
            "role": role_of(pick), "source_sex": facts.get("source_sex", ""), "source_age": facts.get("source_age", ""),
            "expected_instances": pick["n"], "instances": facts["instances"],
            "bytes": zip_path.stat().st_size if zip_path.exists() else 0, "dcm_bytes": facts.get("dcm_bytes", 0),
            "downloaded_at": downloaded, "sha256": sha256_of(zip_path) if zip_path.exists() else "",
            "transfer_syntax": facts.get("transfer_syntax", ""), "photometric": facts.get("photometric", ""),
            "rows": facts.get("rows", ""), "columns": facts.get("columns", ""),
            "burned_in_annotation": facts.get("burned_in_annotation", ""),
            "burned_in": burned_in_value(facts.get("burned_in_annotation", ""), text),
            "face_check_required": face_check_required(pick), "face_check_method": q.get("face_check_method", ""),
            "deface_check": deface, "instances_removed": removed, "text_check": text,
            "z_extent_mm": facts.get("z_extent_mm", ""),
            "status": "downloaded" if complete else "missing",
            "download_url": f"{NBIA}/getImage?SeriesInstanceUID={pick['series']}",
            "notes": "; ".join(n for n in notes if n), "raw_dir": str(d),
        })
    return rows


def write_manifest(root=DEFAULT_ROOT, rows=None):
    root = Path(root)
    rows = build_rows(root) if rows is None else rows
    out = {"library": "Vaidyx-TB demo PACS public-image library", "root": str(root),
           "built_at": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
           "tcia_citation": TCIA_CITATION, "tcga_acknowledgement": TCGA_ACK,
           "collections": {k: {"licence_name": v["licence"][0], "licence_url": v["licence"][1], "doi": v["doi"],
                               "page": v["page"], "citation": v["citation"], "origin_country": v["origin"],
                               "tcga_acknowledgement": bool(v.get("tcga")), "acknowledgement": v.get("ack", "")}
                           for k, v in COLLECTIONS.items()},
           "series": rows}
    (root / "MANIFEST.json").write_text(json.dumps(out, indent=1))
    with open(root / "MANIFEST.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=MANIFEST_FIELDS)
        w.writeheader()
        for r in rows:
            r2 = dict(r)
            r2["instances_removed"] = ";".join(str(x) for x in r["instances_removed"])
            w.writerow(r2)
    return out


def load_manifest(path):
    """MANIFEST.json -> list of series rows (what relabel.plan_assignment reads)."""
    data = json.loads(Path(path).read_text())
    return data["series"] if isinstance(data, dict) else data


